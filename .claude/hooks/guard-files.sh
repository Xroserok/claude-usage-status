#!/bin/bash
# PreToolUse(Edit|Write): protect the files the agent must not change.
INPUT=$(cat)
FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // empty')
# Write sends .content, Edit sends .new_string, MultiEdit sends .edits[].new_string.
TEXT=$(printf '%s' "$INPUT" | jq -r '[.tool_input.content, .tool_input.new_string, (.tool_input.edits // [])[].new_string] | map(select(. != null)) | join("\n")')

deny() {
  echo "Blocked by YourLimit policy: $1. See CLAUDE.md 'Hard rules'. If you believe this is needed, stop and ask." >&2
  exit 2
}

case "$FILE" in
  *.entitlements)              deny "no entitlements: ad-hoc signing, no sandbox (spec §4.4)" ;;
  *.xcodeproj/*|*.xcworkspace/*|*/Derived/*)
                               deny "generated by Tuist; edit Project.swift and run tuist generate" ;;
  *"Claude Code-credentials"*) deny "Claude Code's Keychain item is read-only for this project" ;;
esac

if [[ "$FILE" == *Package.swift ]] && printf '%s' "$TEXT" | grep -q '\.package(url'; then
  deny "no third-party packages (CLAUDE.md). Local packages use .package(path:)"
fi

if printf '%s' "$TEXT" | grep -Eq 'sk-ant-oat01-[A-Za-z0-9_-]{20,}'; then
  deny "an OAuth token is about to be written to $FILE; tokens never go into files, fixtures or tests"
fi
exit 0
